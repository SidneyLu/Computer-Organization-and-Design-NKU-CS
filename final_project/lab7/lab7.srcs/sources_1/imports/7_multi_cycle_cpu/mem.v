module mem(                          // ???
    input              clk,          // ???
    input              MEM_valid,    // ?????????
    input      [105:0] EXE_MEM_bus_r,// EXE->MEM????
    input      [ 31:0] dm_rdata,     // ????????
    output     [ 31:0] dm_addr,      // ????????
    output reg [  3:0] dm_wen,       // ???????
    output reg [ 31:0] dm_wdata,     // ????????
    output             MEM_over,     // MEM?????????
    output    [ 69:0] MEM_WB_bus,   // MEM->WB????
    
    //??PC
