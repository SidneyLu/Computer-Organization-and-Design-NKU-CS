//-----{EXE->MEM????}begin
    //???????????load/store???
    wire [3 :0] mem_control;  //MEM?????????????
    wire [31:0] store_data;   //store????????????
    
    //alu??????
    wire [31:0] alu_result;
    
    //??????????????
    wire       rf_wen;    //????????????
    wire [4:0] rf_wdest;  //???????????
    
    //pc
    wire [31:0] pc;    
    assign {mem_control,
            store_data,
            alu_result,
            rf_wen,
            rf_wdest,
            pc         } = EXE_MEM_bus_r;  
//-----{EXE->MEM????}end

//-----{load/store???}begin
    wire inst_load;  //load????
    wire inst_store; //store????
    wire ls_word;    //load/store?????????,0:byte;1:word
    wire lb_sign;    //load??????????load
    assign {inst_load,inst_store,ls_word,lb_sign} = mem_control;

    //????????
    assign dm_addr = alu_result;
    
    //store??????????
    always @ (*)    // ??????????
    begin
        if (MEM_valid && inst_store) // ???????,???store????
        begin
            if (ls_word)
            begin
                dm_wen <= 4'b1111; // ????????????1
            end
            else
            begin // SB???????????????????????????????
                case (dm_addr[1:0])
                    2'b00   : dm_wen <= 4'b0001;
                    2'b01   : dm_wen <= 4'b0010;
                    2'b10   : dm_wen <= 4'b0100;
                    2'b11   : dm_wen <= 4'b1000;
                    default : dm_wen <= 4'b0000;
                endcase
            end
        end
        else
        begin
            dm_wen <= 4'b0000;
        end
    end 
    
    //store???????????
    always @ (*)  // ????SB??????????????????????store?????????????
    begin
        case (dm_addr[1:0])
            2'b00   : dm_wdata <= store_data;
            2'b01   : dm_wdata <= {16'd0, store_data[7:0], 8'd0};
            2'b10   : dm_wdata <= {8'd0, store_data[7:0], 16'd0};
            2'b11   : dm_wdata <= {store_data[7:0], 24'd0};
            default : dm_wdata <= store_data;
        endcase
    end
    
     //load??????????
     wire        load_sign;
     wire [31:0] load_result;
     assign load_sign = (dm_addr[1:0]==2'd0) ? dm_rdata[ 7] :
                        (dm_addr[1:0]==2'd1) ? dm_rdata[15] :
                        (dm_addr[1:0]==2'd2) ? dm_rdata[23] : dm_rdata[31] ;
     assign load_result[7:0] = (dm_addr[1:0]==2'd0) ? dm_rdata[ 7:0 ] :
                               (dm_addr[1:0]==2'd1) ? dm_rdata[15:8 ] :
                               (dm_addr[1:0]==2'd2) ? dm_rdata[23:16] :
                                                      dm_rdata[31:24] ;
     assign load_result[31:8]= ls_word ? dm_rdata[31:8] :
                                         {24{lb_sign & load_sign}};
//-----{load/store???}end

//-----{MEM??????}begin
