`define STARTADDR 32'd0   // ???????????0
module fetch(                    // ????
    input             clk,       // ???
    input             resetn,    // ??????????????
    input             IF_valid,  // ??????????
    input             next_fetch,// ?????????????????PC?
    input      [31:0] inst,      // inst_rom????????
    input      [32:0] jbr_bus,   // ???????
    output     [31:0] inst_addr, // ????inst_rom???????
     output reg        IF_over,   // IF?????????
    output     [63:0] IF_ID_bus, // IF->ID????
    
    //??PC??????????
    output     [31:0] IF_pc,
    output     [31:0] IF_inst
);

//-----{?????????PC}begin
    wire [31:0] next_pc;
    wire [31:0] seq_pc;
    reg  [31:0] pc;
    reg  [31:0] pc_buf;
    //???pc
    wire        jbr_taken;
    wire [31:0] jbr_target;
    assign {jbr_taken, jbr_target} = jbr_bus; //???????
    
    assign seq_pc[31:2]  = pc[31:2] + 1'b1;   //??????????PC=PC+4
    assign seq_pc[1 :0]  = pc[1:0];

    // ???????????????????????????????????
    assign next_pc = jbr_taken ? jbr_target : seq_pc; 
    
    always @(posedge clk)    // PC?????????
    begin
        if (!resetn)
        begin
            pc <= `STARTADDR; // ????????????????
            pc_buf <= `STARTADDR;
        end
        else if (next_fetch)
        begin
            pc <= next_pc;    // ?????????????
        end
        if (IF_valid)
        begin
            // inst_rom is synchronous; latch the request PC that matches
            // the instruction word visible in the current fetch cycle.
            pc_buf <= pc;
        end
    end
//-----{?????????PC}end

//-----{????inst_rom???????}begin
    assign inst_addr = pc;
//-----{????inst_rom???????}end

//-----{IF??????}begin
    //???????rom?????????,
    //????????????????
    //??????????????????????????????
    //?????????????????
    //??IF_valid??????????IF_over???
   always @(posedge clk)
    begin
        if (!resetn || next_fetch)
        begin
            IF_over <= 1'b0;
        end
        else
        begin
            IF_over <= IF_valid;
        end
    end
    //??????rom??????????IF_valid????IF_over????
    //??????????
//-----{IF??????}end

//-----{IF->ID????}begin
    assign IF_ID_bus = {pc_buf, inst};
//-----{IF->ID????}end

//-----{??IF????PC??????}begin
    assign IF_pc   = pc_buf;
    assign IF_inst = inst;
//-----{??IF????PC??????}end
endmodule


