`define EXC_ENTER_ADDR 32'd0     // Excption???????
                                 // ???????Exception???SYSCALL
module wb(                       // ????
    input          WB_valid,     // ???????
    input  [117:0] MEM_WB_bus_r, // MEM->WB????
    output         rf_wen,       // ?????????
    output [  4:0] rf_wdest,     // ?????????
    output [ 31:0] rf_wdata,     // ??????????
    output         WB_over,      // WB?????????

     //5????????????
     input             clk,       // ???
    input             resetn,    // ??????????????
     output [ 32:0] exc_bus,      // Exception pc????
     output [  4:0] WB_wdest,     // WB????????????????????
     output         cancel,       // syscall??eret?????????????cancel????
                                  // ???????????????????????????????
 
     //??PC??HI/LO?
     output [ 31:0] WB_pc,
     output [ 31:0] HI_data,
     output [ 31:0] LO_data
);
//-----{MEM->WB????}begin    
    //MEM??????result
    wire [31:0] mem_result;
    //HI/LO????
    wire [31:0] lo_result;
    wire        hi_write;
    wire        lo_write;
    
    //????????????????
    wire wen;
    wire [4:0] wdest;
    
    //??????????????
    wire mfhi;
    wire mflo;
    wire mtc0;
    wire mfc0;
    wire [7 :0] cp0r_addr;
    wire       syscall;   //syscall??eret???????????????? 
    wire       eret;
    
    //pc
    wire [31:0] pc;    
    assign {wen,
            wdest,
            mem_result,
            lo_result,
            hi_write,
            lo_write,
            mfhi,
            mflo,
            mtc0,
            mfc0,
            cp0r_addr,
            syscall,
            eret,
            pc} = MEM_WB_bus_r;
//-----{MEM->WB????}end

//-----{HI/LO?????}begin
    //HI??????????????32?
    //LO??????????????32?
    reg [31:0] hi;
    reg [31:0] lo;
    
    //????HI??????????mem_result??
    always @(posedge clk)
    begin
        if (hi_write)
        begin
            hi <= mem_result;
        end
    end
    //????LO??????????lo_result??
    always @(posedge clk)
    begin
        if (lo_write)
        begin
            lo <= lo_result;
        end
    end
//-----{HI/LO?????}end

//-----{cp0?????}begin
// cp0????????????????0?????
// ??????????CPU???????????????cp0??????????
// ?????????STATUS(12.0),CAUSE(13.0),EPC(14.0)??????
// ???CP0????????????5???cp0??
   wire [31:0] cp0r_status;
   wire [31:0] cp0r_cause;
   wire [31:0] cp0r_epc;
   
   //????
   wire status_wen;
   //wire cause_wen;
   wire epc_wen;
   assign status_wen = mtc0 & (cp0r_addr=={5'd12,3'd0});
   assign epc_wen    = mtc0 & (cp0r_addr=={5'd14,3'd0});
   
   //cp0???????
   wire [31:0] cp0r_rdata;
   assign cp0r_rdata = (cp0r_addr=={5'd12,3'd0}) ? cp0r_status :
                       (cp0r_addr=={5'd13,3'd0}) ? cp0r_cause  :
                       (cp0r_addr=={5'd14,3'd0}) ? cp0r_epc : 32'd0;
   
   //STATUS?????
   //??????STATUS[1]?????EXL??
   //EXL?????????????????statu_wen
   reg status_exl_r;
   assign cp0r_status = {30'd0,status_exl_r,1'b0};
   always @(posedge clk)
   begin
       if (!resetn || eret)
       begin
           status_exl_r <= 1'b0;
       end
       else if (syscall)
       begin
           status_exl_r <= 1'b1;
       end
       else if (status_wen)
       begin
           status_exl_r <= mem_result[1];
       end
   end
   
   //CAUSE?????
   //??????CAUSE[6:2]?????ExcCode??,???Exception????
   //ExcCode????????????????????????cause_wen
   reg [4:0] cause_exc_code_r;
   assign cp0r_cause = {25'd0,cause_exc_code_r,2'd0};
   always @(posedge clk)
   begin
       if (syscall)
       begin
           cause_exc_code_r <= 5'd8;
       end
   end
   
   //EPC?????
   //?????????????
   //EPC??????????????????????epc_wen
   reg [31:0] epc_r;
   assign cp0r_epc = epc_r;
   always @(posedge clk)
   begin
       if (syscall)
       begin
           epc_r <= pc;
       end
       else if (epc_wen)
       begin
           epc_r <= mem_result;
       end
   end
   
   //syscall??eret??????cancel???
   assign cancel = (syscall | eret) & WB_over;
//-----{cp0?????}begin

//-----{WB??????}begin
    //WB????????????????????????
    //??WB_valid????WB_over???
    assign WB_over = WB_valid;
//-----{WB??????}end

//-----{WB->regfile???}begin
    assign rf_wen   = wen & WB_over;
    assign rf_wdest = wdest;
    assign rf_wdata = mfhi ? hi :
                      mflo ? lo :
                      mfc0 ? cp0r_rdata : mem_result;
//-----{WB->regfile???}end

//-----{Exception pc???}begin
    wire        exc_valid;
    wire [31:0] exc_pc;
    assign exc_valid = (syscall | eret) & WB_valid;
    //eret???????EPC????????
    //SYSCALL??excPC????{EBASE[31:10],10'h180},
    //??????????????EXC_ENTER_ADDR?0???????????????
    assign exc_pc = syscall ? `EXC_ENTER_ADDR : cp0r_epc;
    
    assign exc_bus = {exc_valid,exc_pc};
//-----{Exception pc???}end

//-----{WB????dest?}begin
   //?????WB??????????????????????????????
    assign WB_wdest = rf_wdest & {5{WB_valid}};
//-----{WB????dest?}end

//-----{??WB????PC???HI/LO????????}begin
    assign WB_pc = pc;
    assign HI_data = hi;
    assign LO_data = lo;
//-----{??WB????PC???HI/LO????????}end
endmodule



